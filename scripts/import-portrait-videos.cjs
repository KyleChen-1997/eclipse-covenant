'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
// Only register actual, recognizable video containers. Missing files retain existing artwork.
const legacyFiles={sirius:'hero1.mp4',morwen:'hero3.mp4',thalor:'hero4.mp4',nullion:'hero5.mp4',causalia:'hero6.mp4'};
function collectVideos(directory,heroes){
  const result={};
  for(const hero of heroes.filter(h=>['UR','SP','SSP'].includes(h.rarity))){
    const choices=['mp4','webm'].map(ext=>hero.id+'.'+ext).filter(file=>fs.existsSync(path.join(directory,file)));
    if(choices.length>1)throw new Error(`${hero.id}: keep only one of .mp4 or .webm to avoid ambiguous selection`);
    const file=choices[0]||(legacyFiles[hero.id]&&fs.existsSync(path.join(directory,legacyFiles[hero.id]))?legacyFiles[hero.id]:null);
    if(!file)continue;
    const target=path.join(directory,file),stat=fs.statSync(target);
    if(!stat.isFile()||stat.size<16||stat.size>=95*1024*1024)throw new Error(`${file}: expected a nonempty video smaller than 95 MiB`);
    const header=Buffer.alloc(16),fd=fs.openSync(target,'r');try{fs.readSync(fd,header,0,16,0);}finally{fs.closeSync(fd);}
    if(file.endsWith('.mp4')?header.toString('ascii',4,8)!=='ftyp':header.toString('hex',0,4)!=='1a45dfa3')throw new Error(`${file}: unrecognized video container; do not rename an image to .mp4`);
    result[hero.id]='assets/videos/'+file;
  }
  return result;
}
function serialize(map){return '// Generated by npm run portraits:import. Register only files present on disk.\n(function(root){const videos='+JSON.stringify(map,null,2)+';if(typeof module!=="undefined"&&module.exports)module.exports=videos;else root.EclipsePortraitVideos=videos;})(typeof globalThis!=="undefined"?globalThis:this);\n';}
if(require.main===module){
  try{const C=require('../eclipse/core.js'),videos=collectVideos(path.join(root,'eclipse/assets/videos'),C.HEROES),out=path.join(root,'eclipse/portrait-videos.js'),content=serialize(videos);if(!fs.existsSync(out)||fs.readFileSync(out,'utf8')!==content)fs.writeFileSync(out,content);console.log(`Video portraits: ${Object.keys(videos).length} / ${C.HEROES.filter(h=>C.rankOf(h)>=4).length}; missing videos keep their existing illustrations. Container checks do not replace visual playback review.`);}catch(error){console.error(error.message);process.exitCode=1;}
}
module.exports={collectVideos,serialize};
